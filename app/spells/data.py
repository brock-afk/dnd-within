"""Spells from the 2024 Player's Handbook. Synced into the `spells` table on startup.

So far this only covers the Wizard's cantrips and level 1 spells. Summaries are short
reminders written for this app, not the book's rules text.
"""

import re


def _spell(
    name: str,
    level: int,
    school: str,
    casting_time: str,
    range: str,
    components: str,
    duration: str,
    summary: str,
    *,
    concentration: bool = False,
    ritual: bool = False,
    classes: tuple[str, ...] = ("wizard",),
) -> dict:
    return {
        "slug": re.sub(r"[^a-z0-9]+", "-", name.lower().replace("'", "")).strip("-"),
        "name": name,
        "level": level,
        "school": school,
        "casting_time": casting_time,
        "range": range,
        "components": components,
        "duration": duration,
        "concentration": concentration,
        "ritual": ritual,
        "summary": summary,
        "classes": list(classes),
    }


